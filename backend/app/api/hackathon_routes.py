@router.post("/github-review/{analysis_id}")
async def create_github_review(analysis_id: str):
    a = store.get(analysis_id)
    if not a:
        raise HTTPException(404, detail="Analysis not found")
    cfg = config_store.get_all()
    token = cfg.get("github_token")
    if not token:
        raise HTTPException(400, detail="Configure a GitHub token before writing review comments")
    if not a.source_url:
        raise HTTPException(400, detail="This analysis is not linked to a GitHub pull request")
    match = re.match(r"https://github\.com/([^/]+)/([^/]+)/pull/(\d+)", a.source_url)
    if not match:
        raise HTTPException(400, detail="Unsupported GitHub pull request URL")
    owner, repo, pr = match.groups()
    headers = {
        "Accept": "application/vnd.github+json",
        "Authorization": f"Bearer {token}",
        "User-Agent": "ChangeGuard/0.6",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    url = f"https://api.github.com/repos/{owner}/{repo}/issues/{pr}/comments"
    async with httpx.AsyncClient(timeout=20, headers=headers) as client:
        response = await client.post(url, json={"body": _analysis_report_md(a)})
    if response.status_code >= 400:
        detail = f"GitHub returned HTTP {response.status_code}"
        if response.headers.get("content-type", "").startswith("application/json"):
            detail = response.json().get("message", detail)
        raise HTTPException(response.status_code, detail=detail)
    data = response.json()
    return {"ok": True, "url": data.get("html_url"), "comment_id": data.get("id")}


@router.get("/submission-status")
async def submission_status():
    latest = config_store.latest_benchmark()
    analyses = store.list_full(limit=100)
    has_agentic = bool(latest and latest.get("benchmark_type") == "single-prompt-vs-agentic")
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "checks": [
            {"name": "Real GitHub PR analysis", "ready": bool(analyses)},
            {"name": "Representative trajectories", "ready": any(a.trajectory for a in analyses)},
            {"name": "15-case benchmark dataset", "ready": True},
            {"name": "Same-model single-prompt baseline", "ready": True},
            {"name": "Official agentic benchmark executed", "ready": has_agentic},
            {"name": "Reproduction guide", "ready": True},
            {"name": "Improvement changelog", "ready": True},
            {"name": "5-minute demo script", "ready": True},
        ],
    }
